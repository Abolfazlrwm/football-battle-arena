// Scans public/logos for {slug}.webp and writes src/data/logos.generated.ts so the app
// only requests logo files that exist (no 400s for missing ones; those use the crest).
// Runs automatically before `npm run dev` and `npm run build`.
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "public", "logos");
const slugs = fs.existsSync(dir)
  ? fs.readdirSync(dir).filter((f) => f.endsWith(".webp")).map((f) => f.replace(/\.webp$/, "")).sort()
  : [];

const out = `// AUTO-GENERATED by scripts/gen-logo-manifest.mjs — do not edit by hand.
// Slugs that have a file in public/logos/{slug}.webp.
export const AVAILABLE_LOGOS: readonly string[] = ${JSON.stringify(slugs, null, 2)};
`;
fs.writeFileSync(path.join(process.cwd(), "src", "data", "logos.generated.ts"), out);
console.log(`logo manifest: ${slugs.length} logo file(s)`);
